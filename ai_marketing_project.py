def run_guardrail_and_export():
    """Validates generated copy against brand rules and packages deliverables."""

    with open("brand_kit.json", "r") as f:
        brand_kit = json.load(f)

    try:
        with open("generated_copy.txt", "r") as f:
            copy_content = f.read()
    except FileNotFoundError:
        print("System Flag: generated_copy.txt not found. Aborting export.")
        return

    print("Executing brand consistency guardrail analysis...\n")
    guardrail_passed = True

    # Rule validation
    for word in brand_kit["dont_say_words"]:
        if word.lower() in copy_content.lower():
            print(f"WARNING: Brand violation detected. Banned word '{word}' found.")
            guardrail_passed = False

    if guardrail_passed:
        print("Validation Status: Passed. Zero brand violations detected.\n")

    print("Assembling final client deliverables...\n")

    # Bonus: Simulated token cost tracking for agency billing
    estimated_tokens = len(copy_content.split()) * 1.3
    estimated_cost = round((estimated_tokens / 1000) * 0.002, 4) # Standard LLM pricing

    with open("Campaign_Summary.txt", "w") as f:
        f.write("=== AI MARKETING AGENCY-IN-A-BOX ===\n")
        f.write(f"Client / Brand Name: {brand_kit['brand_name']}\n")
        f.write(f"Guardrail Status: {'Passed' if guardrail_passed else 'Failed'}\n")
        f.write(f"Estimated API Cost: ${estimated_cost} USD\n\n")
        f.write("=== FINAL CHANNEL COPY ===\n")
        f.write(copy_content)

    zip_filename = "Final_Marketing_Package.zip"
    with zipfile.ZipFile(zip_filename, 'w') as zipf:
        zipf.write("brand_kit.json")
        zipf.write("generated_copy.txt")
        zipf.write("Campaign_Summary.txt")

    print(f"System Export Complete. Package ready: {zip_filename}")

# Execute export
run_guardrail_and_export()